// Generates the exercise-library migration from free-exercise-db (public domain, Unlicense).
// Usage: node scripts/generate-exercise-seed.mjs path/to/exercises.json > supabase/migrations/<ts>_seed_exercises.sql
// Source: https://github.com/yuhonas/free-exercise-db (dist/exercises.json)
import { readFileSync } from 'node:fs'

const exercises = JSON.parse(readFileSync(process.argv[2], 'utf8'))
  // Stretches aren't logged as working sets; leave them out to keep the library focused.
  .filter((e) => e.category !== 'stretching')
  .sort((a, b) => a.id.localeCompare(b.id))

const str = (v) => (v == null ? 'null' : `'${String(v).replaceAll("'", "''")}'`)
const arr = (v) => (v?.length ? `array[${v.map(str).join(',')}]` : `'{}'`)

const rows = exercises.map((e) =>
  `(${[str(e.id), str(e.name), arr(e.primaryMuscles), arr(e.secondaryMuscles), str(e.equipment), str(e.mechanic),
    str(e.force), str(e.level), str(e.category), arr(e.images)].join(', ')})`,
)

process.stdout.write(`-- Exercise library: ${exercises.length} exercises from free-exercise-db (public domain).
-- Generated by scripts/generate-exercise-seed.mjs. Safe to re-run: existing rows are updated.
-- ids are derived from the source id (md5 → uuid) so they are identical in every database.
insert into public.exercises
  (id, source, source_id, name, primary_muscles, secondary_muscles, equipment, mechanic, force, level, category, images)
select md5('free-exercise-db:' || v.source_id)::uuid, 'free-exercise-db', v.source_id, v.name,
       v.primary_muscles::text[], v.secondary_muscles::text[], v.equipment, v.mechanic, v.force, v.level, v.category,
       v.images::text[]
from (values
${rows.join(',\n')}
) as v (source_id, name, primary_muscles, secondary_muscles, equipment, mechanic, force, level, category, images)
on conflict (source, source_id) where source_id is not null do update set
  name = excluded.name,
  primary_muscles = excluded.primary_muscles,
  secondary_muscles = excluded.secondary_muscles,
  equipment = excluded.equipment,
  mechanic = excluded.mechanic,
  force = excluded.force,
  level = excluded.level,
  category = excluded.category,
  images = excluded.images;
`)
